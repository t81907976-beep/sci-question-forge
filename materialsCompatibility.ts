function pairKey(a: string, b: string): string {
    return [a, b].sort().join('||');
}

const STRONG_SET = new Set(STRONG_PAIRS.map(([a, b]) => pairKey(a, b)));
const MODERATE_SET = new Set(MODERATE_PAIRS.map(([a, b]) => pairKey(a, b)));

/** 两个方向的融合兼容度 */
export function getCompatLevel(a: string, b: string): CompatLevel {
    if (a === b) return 'strong';
    if (UNIVERSAL.has(a) || UNIVERSAL.has(b)) return 'strong';
    const key = pairKey(a, b);
    if (STRONG_SET.has(key)) return 'strong';
    if (MODERATE_SET.has(key)) return 'moderate';
    return 'weak';
}

export interface CombinationCheck {
    /** 是否可以融合成一道跨领域题 */
    canFuse: boolean;
    /** 若不能融合,列出低兼容对 */
    weakPairs: Array<[string, string]>;
    /** 若可融合,建议的融合模式提示 */
    fusionHint: string;
}

/** 检查一组方向能否融合 */
export function checkCombination(names: string[]): CombinationCheck {
    if (names.length <= 1) {
        return { canFuse: true, weakPairs: [], fusionHint: '' };
    }
    const weakPairs: Array<[string, string]> = [];
    let hasModerate = false;
    for (let i = 0; i < names.length; i++) {
        for (let j = i + 1; j < names.length; j++) {
            const level = getCompatLevel(names[i], names[j]);
            if (level === 'weak') {
                weakPairs.push([names[i], names[j]]);
            } else if (level === 'moderate') {
                hasModerate = true;
            }
        }
    }
    if (weakPairs.length > 0) {
        return {
            canFuse: false,
            weakPairs,
            fusionHint: '',
        };
    }
    return {
        canFuse: true,
        weakPairs: [],
        fusionHint: hasModerate
            ? `将融合 ${names.length} 个方向出跨领域题(部分方向为中等兼容,注意题面自洽性)`
            : `将融合 ${names.length} 个方向出跨领域交叉题`,
    };
}

/** 返回所有可选方向名称(用于渲染多选列表) */
export function getAllMaterialsDisciplineNames(): string[] {
    return Object.values(MATERIALS_DISCIPLINES).map(d => d.name);
}
