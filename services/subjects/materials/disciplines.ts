export function getQuestionTypeAffinity(topic: string, questionType: MaterialsQuestionType): QuestionTypeAffinity {
    const exact = MATERIALS_TYPE_AFFINITY[topic];
    if (exact) return exact[questionType] || 'neutral';

    // 自由文本 topic：退化为 name 子串匹配
    for (const [name, affinity] of Object.entries(MATERIALS_TYPE_AFFINITY)) {
        if (topic.includes(name)) return affinity[questionType] || 'neutral';
    }
    return 'neutral';
}
