// 找出 topic 中所有匹配到的学科方向（支持跨领域融合题）
function findMatchedDisciplines(topic: string): Array<typeof MATERIALS_DISCIPLINES[keyof typeof MATERIALS_DISCIPLINES]> {
    // 第一优先级：按 name 精确/子串匹配。
    // UI 传下来的 topic 恒为 discipline.name（单选），跨领域融合题 topic 形如
    // "跨领域融合题:A × B" 亦含完整 name 全串，因此 UI 路径永远命中此处。
    // 细分方向（如"力学性能-疲劳"）与其母方向（"金属材料-力学性能与断裂"）
    // 共享关键词（"疲劳"），若把 name 命中与 keyword 命中同等对待，会导致
    // 单选细分方向时同时命中母方向，被误判为跨领域融合、注入双份约束。
    // 故 name 命中优先：只要有任一 name 命中，就只返回 name 命中集合。
    const nameMatched: Array<typeof MATERIALS_DISCIPLINES[keyof typeof MATERIALS_DISCIPLINES]> = [];
    const seenName = new Set<string>();
    for (const discipline of Object.values(MATERIALS_DISCIPLINES)) {
        if (topic.includes(discipline.name) && !seenName.has(discipline.name)) {
            nameMatched.push(discipline);
            seenName.add(discipline.name);
        }
    }
    if (nameMatched.length > 0) return nameMatched;

    // 第二优先级（兜底）：仅当没有任何 name 命中时（如自由文本 topic），
    // 才退化为 keyword 子串匹配。
    const kwMatched: Array<typeof MATERIALS_DISCIPLINES[keyof typeof MATERIALS_DISCIPLINES]> = [];
    const seenKw = new Set<string>();
    for (const discipline of Object.values(MATERIALS_DISCIPLINES)) {
        if (discipline.keywords.some((kw: string) => topic.includes(kw)) && !seenKw.has(discipline.name)) {
            kwMatched.push(discipline);
            seenKw.add(discipline.name);
        }
    }
    return kwMatched;
}

// 根据主题匹配学科方向，返回出题指导信息（单方向或跨领域融合均支持）
export function getDisciplineGuidance(topic: string): string {
    const matched = findMatchedDisciplines(topic);
    if (matched.length === 0) return '';

    // 单方向：直接输出该方向的完整指导
    if (matched.length === 1) {
        const d = matched[0];
        return [
            `【学科方向】${d.name}`,
            `【难度天花板】${d.peak_difficulty}`,
            `【禁止犯的错误】\n${d.forbidden_errors.join('\n')}`,
            `【参数约束】\n${Object.entries(d.parameter_constraints).map(([k, v]) => `- ${k}: ${v}`).join('\n')}`,
            `【反模式出题策略】\n${d.anti_pattern_strategies.join('\n')}`,
        ].join('\n\n');
    }

    // 多方向：融合注入每个方向的约束（禁忌错误、参数约束、反模式策略均取并集），
    // 保证跨领域题也受完整的学科纪律约束
    const forbidden = matched.flatMap(d => d.forbidden_errors.map(err => `[${d.name}] ${err}`));
    const constraints = matched.flatMap(d =>
        Object.entries(d.parameter_constraints).map(([k, v]) => `- [${d.name}] ${k}: ${v}`)
    );
    const antiPatterns = matched.flatMap(d => d.anti_pattern_strategies.map(s => `[${d.name}] ${s}`));
    const peaks = matched.map(d => `- ${d.name}: ${d.peak_difficulty}`).join('\n');

    return [
        `【跨领域融合方向】${matched.map(d => d.name).join(' × ')}`,
        `【各方向难度天花板】\n${peaks}`,
        `【禁止犯的错误（所有方向并集）】\n${forbidden.join('\n')}`,
        `【参数约束（所有方向并集）】\n${constraints.join('\n')}`,
        `【反模式出题策略（所有方向并集）】\n${antiPatterns.join('\n')}`,
        `【跨领域出题额外要求】题目必须真正体现上述所有方向的交叉，而不是简单堆叠。请找到一个物理机制或工程场景，让不同方向的核心概念自然耦合（如"薄膜与表面工程 × 半导体材料"可用外延生长中的能带工程作为耦合点）。`,
    ].join('\n\n');
}

