// ============================================================
// 题型支持能力（简答/计算）查询
// 每个知识点声明 supportedTypes；当前默认全部支持两种，后续可按需收窄。
// 该机制仅材料学科使用，不影响其它学科。
// ============================================================

const DEFAULT_MATERIALS_TYPES: MaterialsQuestionType[] = ['calculation', 'short-answer'];

/**
 * 根据知识点（name 或 topic 文本）返回其支持的题型列表。
 * - 精确匹配 discipline.name 优先
 * - 否则退化为 findMatchedDisciplines 的匹配结果取并集
 * - 无匹配时返回默认（两种都支持），避免误伤自由文本 topic
 */
export function getSupportedQuestionTypes(topic: string): MaterialsQuestionType[] {
    const exact = Object.values(MATERIALS_DISCIPLINES).find(d => d.name === topic);
    if (exact) return exact.supportedTypes;

    const matched = findMatchedDisciplines(topic);
    if (matched.length === 0) return DEFAULT_MATERIALS_TYPES;

    // 多方向：取并集（任一方向支持该题型即视为支持）
    const union = new Set<MaterialsQuestionType>();
    for (const d of matched) {
        for (const t of d.supportedTypes) union.add(t);
    }
    return union.size > 0 ? Array.from(union) : DEFAULT_MATERIALS_TYPES;
}

/**
 * 判断某知识点是否支持指定题型。无匹配/默认时返回 true（不拦截）。
 */
export function isQuestionTypeSupported(topic: string, questionType: MaterialsQuestionType): boolean {
    return getSupportedQuestionTypes(topic).includes(questionType);
}

